// Pure helpers for the htadb extension (no `vscode` import, so they can be
// unit-tested with plain Node: node --test vscode-extension/test/).
'use strict';

const path = require('path');
const fs = require('fs');

/** VS Code version facts (verified against microsoft/vscode tags):
 *  - 1.109–1.112: `simpleBrowser.useIntegratedBrowser` (application scope,
 *    default false) makes `simpleBrowser.show` open the integrated browser.
 *  - 1.113+: the setting is gone; `simpleBrowser.show` uses the integrated
 *    browser whenever the `workbench.action.browser.open` command exists. */
const INTEGRATED_BROWSER_COMMAND = 'workbench.action.browser.open';

/** Parse "1.112.3" → [1, 112, 3]. */
function parseVersion(v) {
  return String(v).split(/[.-]/).slice(0, 3).map((x) => parseInt(x, 10) || 0);
}

function versionAtLeast(v, min) {
  const a = parseVersion(v);
  const b = parseVersion(min);
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] > b[i];
  return true;
}

/**
 * Decide how simpleBrowser.show will render.
 *  inspect: result of getConfiguration('simpleBrowser').inspect('useIntegratedBrowser') (or undefined)
 *  commands: list from vscode.commands.getCommands(true)
 * Returns {mode, reason, target?}: mode "integrated", "setting-off" (setting
 * exists but is not true → offer Enable…), or "classic" (no integrated browser).
 */
function browserDecision(vscodeVersion, inspect, commands) {
  const hasCommand = commands.includes(INTEGRATED_BROWSER_COMMAND);
  if (versionAtLeast(vscodeVersion, '1.113.0')) {
    return hasCommand
      ? { mode: 'integrated', reason: 'integrated browser available' }
      : { mode: 'classic', reason: 'the integrated browser is not available in this VS Code environment (e.g. VS Code for the Web)' };
  }
  if (!inspect || (inspect.defaultValue === undefined && inspect.globalValue === undefined)) {
    return { mode: 'classic', reason: 'this VS Code has no simpleBrowser.useIntegratedBrowser setting' };
  }
  const effective = firstDefined(inspect.workspaceFolderValue, inspect.workspaceValue, inspect.globalValue, inspect.defaultValue);
  if (effective === true) return { mode: 'integrated', reason: 'simpleBrowser.useIntegratedBrowser is on' };
  return { mode: 'setting-off', reason: 'simpleBrowser.useIntegratedBrowser is off', target: settingTarget(inspect) };
}

function firstDefined(...xs) {
  for (const x of xs) if (x !== undefined) return x;
  return undefined;
}

/** Most specific scope currently overriding the value: folder, workspace or user. */
function settingTarget(inspect) {
  if (inspect.workspaceFolderValue !== undefined) return 'workspaceFolder';
  if (inspect.workspaceValue !== undefined) return 'workspace';
  return 'global';
}

/** Bundled binary path for this platform, e.g. bin/linux-amd64/htadb. */
function bundledBinary(extDir, platform = process.platform, arch = process.arch) {
  const os = { win32: 'windows', darwin: 'darwin', linux: 'linux' }[platform];
  const a = { x64: 'amd64', arm64: 'arm64', arm: 'arm' }[arch];
  if (!os || !a) return null;
  return path.join(extDir, 'bin', `${os}-${a}`, os === 'windows' ? 'htadb.exe' : 'htadb');
}

/** TOML string literal. */
function tomlString(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
}

/** config.toml content for htadb.mirror.devices: {serial: {version, ...options}}. */
function devicesToml(devices) {
  let out = '# Generated by the htadb VS Code extension from htadb.mirror.devices.\n';
  for (const [serial, cfg] of Object.entries(devices || {})) {
    if (!cfg || typeof cfg !== 'object') continue;
    out += `\n[mirror.devices.${tomlString(serial)}]\n`;
    for (const [k, v] of Object.entries(cfg)) {
      if (['string', 'number', 'boolean'].includes(typeof v)) out += `${k.replace(/[^A-Za-z0-9_-]/g, '_')} = ${typeof v === 'string' ? tomlString(v) : String(v)}\n`;
    }
  }
  return out;
}

/** htadb command-line arguments for a managed adapter. */
function adapterArgs(opts) {
  const args = [
    '--listen', `${opts.useTls ? 'https' : 'http'}://127.0.0.1:0`,
    '--announce',
    '--ui-config', opts.uiConfigPath,
    '--config-file', opts.configTomlPath,
    `--mirror-fallback=${opts.fallback !== false}`,
  ];
  if (opts.serverVersion && opts.serverVersion !== 'auto') args.push('--mirror-default-version', opts.serverVersion);
  if (opts.xtermDir) args.push('--ui-override', `/vendor/xterm=${opts.xtermDir}`);
  return args.concat(opts.extraArgs || []);
}

/** Parse "HTADB_LISTENING <url>" announcements. */
function parseAnnounce(line) {
  const m = /^HTADB_LISTENING (\S+)/.exec(line.trim());
  return m ? m[1] : null;
}

/** Candidate locations of VS Code's own xterm.js package under appRoot. */
function xtermCandidates(appRoot) {
  return [
    path.join(appRoot, 'node_modules', '@xterm', 'xterm'),
    path.join(appRoot, 'node_modules.asar.unpacked', '@xterm', 'xterm'),
    path.join(appRoot, 'node_modules.asar', '@xterm', 'xterm'), // readable through Electron's asar fs
  ];
}

/**
 * Find a usable copy of VS Code's xterm.js: version 5+ with the UMD build
 * that defines the global `Terminal` (what htadb's pages load). Returns
 * {dir, version} or {reason}.
 */
function findVSCodeXterm(appRoot, readFile = fs.readFileSync) {
  for (const dir of xtermCandidates(appRoot)) {
    let pkg;
    try { pkg = JSON.parse(readFile(path.join(dir, 'package.json'), 'utf8')); } catch { continue; }
    const major = parseVersion(pkg.version)[0];
    if (major < 5) return { reason: `VS Code's xterm.js ${pkg.version} is too old (need 5+)` };
    let js;
    try { js = readFile(path.join(dir, 'lib', 'xterm.js'), 'utf8'); } catch { return { reason: `VS Code's xterm.js ${pkg.version} has no lib/xterm.js UMD build` }; }
    if (!/typeof exports|define\(\[\]/.test(js.slice(0, 2000))) return { reason: `VS Code's xterm.js ${pkg.version} is not a UMD build` };
    return { dir, version: pkg.version };
  }
  return { reason: 'VS Code\'s xterm.js was not found under its app root' };
}

/** Short device description for the tree: "model · USB". */
function deviceDescription(d) {
  const model = (d.model || d.product || '').replace(/_/g, ' ');
  let conn = '';
  if (/^emulator-\d+$/.test(d.serial)) conn = 'emulator';
  else if (/:\d+$/.test(d.serial)) conn = 'network';
  else if (d.usb) conn = 'USB';
  const parts = [model, conn].filter(Boolean);
  if (d.state !== 'device') parts.push(d.state);
  return parts.join(' · ');
}

module.exports = {
  INTEGRATED_BROWSER_COMMAND, parseVersion, versionAtLeast, browserDecision, settingTarget, bundledBinary,
  devicesToml, adapterArgs, parseAnnounce, xtermCandidates, findVSCodeXterm, deviceDescription, tomlString,
};
