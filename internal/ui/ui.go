// Package ui serves the web UI under /ui/: the embedded build by default,
// a live directory with --ui-dir, sub-path overrides (--ui-override, used by
// the VS Code extension to serve VS Code's own xterm.js) and a generated
// config.js.
package ui

import (
	"embed"
	"encoding/json"
	"fmt"
	"io/fs"
	"net/http"
	"os"
	"path"
	"sort"
	"strings"
)

//go:embed all:dist
var embedded embed.FS

// Options configures the handler.
type Options struct {
	Dir       string            // serve from disk instead of the embedded build
	Overrides map[string]string // "/vendor/xterm" → directory
	Config    map[string]any    // exposed as config.js
}

// ParseOverride parses "/prefix=/dir".
func ParseOverride(s string) (string, string, error) {
	p, d, ok := strings.Cut(s, "=")
	if !ok || !strings.HasPrefix(p, "/") || d == "" {
		return "", "", fmt.Errorf("bad --ui-override %q (want /prefix=/dir)", s)
	}
	return "/" + strings.Trim(p, "/"), d, nil
}

// Embedded reports whether a built UI is embedded.
func Embedded() bool {
	_, err := fs.Stat(embedded, "dist/index.html")
	return err == nil
}

// Handler returns the /ui/ handler.
func Handler(o Options) (http.Handler, error) {
	var root fs.FS
	if o.Dir != "" {
		if _, err := os.Stat(o.Dir); err != nil {
			return nil, fmt.Errorf("--ui-dir: %w", err)
		}
		root = os.DirFS(o.Dir)
	} else {
		sub, err := fs.Sub(embedded, "dist")
		if err != nil {
			return nil, err
		}
		root = sub
	}
	type ov struct {
		prefix string
		h      http.Handler
	}
	var ovs []ov
	for p, d := range o.Overrides {
		if _, err := os.Stat(d); err != nil {
			return nil, fmt.Errorf("--ui-override %s: %w", p, err)
		}
		ovs = append(ovs, ov{p, http.StripPrefix("/ui"+p, http.FileServer(http.Dir(d)))})
	}
	sort.Slice(ovs, func(i, j int) bool { return len(ovs[i].prefix) > len(ovs[j].prefix) })
	cfg, _ := json.Marshal(o.Config)
	if o.Config == nil {
		cfg = []byte("{}")
	}
	configJS := []byte("// Generated by htadb.\nconst config = " + string(cfg) + ";\nexport default config;\n")
	files := http.StripPrefix("/ui", http.FileServer(http.FS(root)))
	dev := o.Dir != ""
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		p := strings.TrimPrefix(r.URL.Path, "/ui")
		if p == "/config.js" {
			w.Header().Set("Content-Type", "text/javascript; charset=utf-8")
			w.Header().Set("Cache-Control", "no-store")
			w.Write(configJS)
			return
		}
		w.Header().Set("X-Content-Type-Options", "nosniff")
		if dev || strings.HasSuffix(p, ".html") || p == "/" {
			w.Header().Set("Cache-Control", "no-cache")
		}
		for _, o := range ovs {
			if p == o.prefix || strings.HasPrefix(p, o.prefix+"/") {
				o.h.ServeHTTP(w, r)
				return
			}
		}
		if p == "/" || p == "" {
			if _, err := fs.Stat(root, "index.html"); err != nil {
				w.Header().Set("Content-Type", "text/plain; charset=utf-8")
				w.WriteHeader(http.StatusNotFound)
				fmt.Fprintln(w, "htadb: the web UI is not built into this binary. Run `make htadb` (or use --ui-dir ./web).")
				return
			}
		}
		if path.Ext(p) == ".js" || path.Ext(p) == ".mjs" {
			w.Header().Set("Content-Type", "text/javascript; charset=utf-8")
		}
		files.ServeHTTP(w, r)
	}), nil
}
